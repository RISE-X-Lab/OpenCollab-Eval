def test_read_only_probe_suppresses_expected_shell_noise(tmp_path: Path) -> None:
    target = tmp_path / "control-file"
    target.write_text("trusted\n", encoding="utf-8")
    target.chmod(0o400)

    result = subprocess.run(
        [
            "bash",
            "--noprofile",
            "--norc",
            "-c",
            'if (printf x >> "$1") 2>/dev/null; then exit 31; fi',
            "--",
            str(target),
        ],
        text=True,
        capture_output=True,
        check=False,
    )

    assert result.returncode == 0
    assert result.stderr == ""
    assert target.read_text(encoding="utf-8") == "trusted\n"


