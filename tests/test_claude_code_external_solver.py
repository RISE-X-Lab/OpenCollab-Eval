def test_external_sidecar_is_required_and_usage_is_attributed_to_claude_code(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    (tmp_path / "external_solver.required.json").write_text(
        json.dumps(
            {
                "solver": "claude-code",
                "expected_model": "glm-5.2",
                "expected_runtime_image_id": "sha256:" + "a" * 64,
                "task_image_id": TASK_IMAGE_ID,
            }
        ),
        encoding="utf-8",
    )
    with pytest.raises(ValueError, match="missing or malformed"):
        esu._external_solver_evidence(tmp_path)

    sidecar = _build(tmp_path)
    (tmp_path / "external_solver.sidecar.json").write_text(json.dumps(sidecar), encoding="utf-8")
    evidence = esu._external_solver_evidence(tmp_path)
    assert evidence is not None
    repository = tmp_path / "binding-repository"
    repository.mkdir()
    (repository / "value.txt").write_text("baseline\n", encoding="utf-8")
    (repository / ".gitignore").write_text("*.generated\n", encoding="utf-8")
    subprocess.run(["git", "init", "-q", str(repository)], check=True)
    subprocess.run(["git", "-C", str(repository), "add", "value.txt", ".gitignore"], check=True)
    subprocess.run(
        [
            "git",
            "-C",
            str(repository),
            "-c",
            "user.name=Evaluator",
            "-c",
            "user.email=evaluator@example.invalid",
            "commit",
            "-qm",
            "baseline",
        ],
        check=True,
    )
    anonymous_head = subprocess.check_output(["git", "-C", str(repository), "rev-parse", "HEAD"], text=True).strip()
    base_tree = subprocess.check_output(["git", "-C", str(repository), "rev-parse", "HEAD^{tree}"], text=True).strip()
    (repository / "value.txt").write_text("fixed\n", encoding="utf-8")
    (repository / "needed.generated").write_text("required ignored source\n", encoding="utf-8")
    bytecode = repository / "pkg" / "__pycache__" / "runtime.cpython-311.pyc"
    bytecode.parent.mkdir(parents=True)
    bytecode.write_bytes(b"generated bytecode")
    candidate_index = tmp_path / "candidate.index"
    candidate_env = {**os.environ, "GIT_INDEX_FILE": str(candidate_index)}
    subprocess.run(
        ["git", "-C", str(repository), "read-tree", "HEAD"],
        env=candidate_env,
        check=True,
    )
    pathspec = [
        ".",
        ":(exclude).git",
        ":(exclude).git/**",
        ":(exclude).opencollab",
        ":(exclude).opencollab/**",
    ]
    subprocess.run(
        ["git", "-C", str(repository), "add", "-f", "-A", "--", *pathspec],
        env=candidate_env,
        check=True,
    )
    raw_patch = subprocess.check_output(
        [
            "git",
            "-C",
            str(repository),
            "diff",
            "--cached",
            "--binary",
            "HEAD",
            "--",
            *pathspec,
        ],
        env=candidate_env,
        text=True,
    )
    raw_candidate_tree = subprocess.check_output(
        ["git", "-C", str(repository), "write-tree"], env=candidate_env, text=True
    ).strip()
    pre_sanitization_patch = subprocess.check_output(
        [
            "git",
            "-C",
            str(repository),
            "diff",
            "--cached",
            "--binary",
            "--full-index",
            "HEAD",
            "--",
            *pathspec,
        ],
        env=candidate_env,
        text=True,
    )
    subprocess.run(
        ["git", "-C", str(repository), "rm", "-qr", "--cached", "--", bytecode.relative_to(repository)],
        env=candidate_env,
        check=True,
    )
    patch = subprocess.check_output(
        [
            "git",
            "-C",
            str(repository),
            "diff",
            "--cached",
            "--binary",
            "--full-index",
            "HEAD",
            "--",
            *pathspec,
        ],
        env=candidate_env,
        text=True,
    )
    assert "needed.generated" in raw_patch
    assert "__pycache__" in raw_patch
    assert "__pycache__" not in patch
    assert hashlib.sha256(raw_patch.encode()).hexdigest() != hashlib.sha256(patch.encode()).hexdigest()
    candidate_tree = subprocess.check_output(
        ["git", "-C", str(repository), "write-tree"], env=candidate_env, text=True
    ).strip()
    assert raw_candidate_tree != candidate_tree
    hostile_objects = tmp_path / "hostile-objects"
    hostile_objects.mkdir()
    for key, value in {
        "GIT_OBJECT_DIRECTORY": str(hostile_objects),
        "GIT_ALTERNATE_OBJECT_DIRECTORIES": str(hostile_objects),
        "GIT_CONFIG_COUNT": "1",
        "GIT_CONFIG_KEY_0": "core.attributesFile",
        "GIT_CONFIG_VALUE_0": str(tmp_path / "hostile-attributes"),
        "GIT_CONFIG_PARAMETERS": "'core.hooksPath'='/private/tmp/hostile-hooks'",
        "GIT_REPLACE_REF_BASE": "refs/private-replacements/",
    }.items():
        monkeypatch.setenv(key, value)
    assert candidate_tree == esu._candidate_tree_from_patch(repository / ".git", anonymous_head, patch)
    prompt = tmp_path / "claude.prompt.md"
    prompt.write_text("public prompt\n", encoding="utf-8")
    (tmp_path / "claude.patch").write_text(raw_patch, encoding="utf-8")
    patch_sha256 = hashlib.sha256(patch.encode()).hexdigest()
    evidence["invocation_binding"] = {
        "solver_task_id": "solver-" + "1" * 32,
        "prompt_sha256": hashlib.sha256(prompt.read_bytes()).hexdigest(),
        "anonymous_head": anonymous_head,
        "base_tree": base_tree,
        "raw_patch_sha256": hashlib.sha256(raw_patch.encode()).hexdigest(),
        "candidate_tree": raw_candidate_tree,
        "task_image_id": TASK_IMAGE_ID,
    }
    trusted_extraction = {
        "fixed_anonymous_base": anonymous_head,
        "base_tree": base_tree,
        "baseline_archive_sha256": "6" * 64,
        "workspace_archive_sha256": "7" * 64,
        "patch_sha256": patch_sha256,
        "pre_sanitization_patch_sha256": hashlib.sha256(
            pre_sanitization_patch.encode()
        ).hexdigest(),
        "pre_sanitization_candidate_tree": raw_candidate_tree,
        "candidate_tree": candidate_tree,
    }
    binding_args = {
        "output_dir": tmp_path,
        "prompt_file": prompt,
        "solver_task_id": "solver-" + "1" * 32,
        "public_instance_id": "public-instance-7",
        "anonymous_head": anonymous_head,
        "base_tree": base_tree,
        "baseline_git_dir": repository / ".git",
        "patch": patch,
        "run_identity": {"OPENCOLLAB_EVAL_RUN_ID": "claude-union-23"},
    }
    evidence = esu._bind_external_solver_evidence(
        evidence,
        trusted_extraction=trusted_extraction,
        **binding_args,
    )
    identity = esu._external_solver_identity(evidence)
    assert identity["schema"] == "opencollab.external_solver_identity.v1"
    assert identity["model"] == "glm-5.2"
    assert identity["public_instance_id"] == "public-instance-7"
    assert identity["trusted_final_patch_sha256"] == patch_sha256
    assert identity["candidate_tree"] == candidate_tree
    assert evidence["evaluation_binding"]["public_instance_id"] == "public-instance-7"
    assert evidence["evaluation_binding"]["trusted_baseline_sha256"] == "6" * 64
    assert evidence["evaluation_binding"]["raw_patch_sha256"] == hashlib.sha256(raw_patch.encode()).hexdigest()
    assert evidence["evaluation_binding"]["canonical_raw_patch_sha256"] == hashlib.sha256(
        pre_sanitization_patch.encode()
    ).hexdigest()
    assert evidence["evaluation_binding"]["trusted_final_patch_sha256"] == patch_sha256
    assert evidence["evaluation_binding"]["raw_candidate_tree"] == raw_candidate_tree
    assert evidence["evaluation_binding"]["candidate_tree"] == candidate_tree
    original_raw_patch = (tmp_path / "claude.patch").read_text(encoding="utf-8")
    (tmp_path / "claude.patch").write_text(original_raw_patch + "\n", encoding="utf-8")
    with pytest.raises(ValueError, match="raw patch SHA mismatch"):
        esu._bind_external_solver_evidence(
            copy.deepcopy(evidence),
            trusted_extraction=trusted_extraction,
            **binding_args,
        )
    (tmp_path / "claude.patch").write_text(original_raw_patch, encoding="utf-8")
    tampered_evidence = copy.deepcopy(evidence)
    tampered_evidence["invocation_binding"]["candidate_tree"] = "f" * 40
    with pytest.raises(ValueError, match="raw candidate tree mismatch"):
        esu._bind_external_solver_evidence(
            tampered_evidence,
            trusted_extraction=trusted_extraction,
            **binding_args,
        )
    for field, message in (
        ("pre_sanitization_patch_sha256", "canonical patch"),
        ("pre_sanitization_candidate_tree", "does not match trusted extraction"),
        ("candidate_tree", "trusted final candidate tree mismatch"),
    ):
        tampered_extraction = {**trusted_extraction, field: "f" * (64 if "sha256" in field else 40)}
        with pytest.raises(ValueError, match=message):
            esu._bind_external_solver_evidence(
                copy.deepcopy(evidence),
                trusted_extraction=tampered_extraction,
                **binding_args,
            )
    values = esu._external_solver_usage(evidence)
    assert values is not None
    assert values["input_tokens"] == 420
    payload = esu._append_usage_record(
        run_dir=tmp_path,
        instance_id="instance-7",
        model="glm-5.2",
        usage_values=values,
        provider="claude-code",
        label="claude-code-aggregate",
    )
    record = json.loads((tmp_path / "api_usage.jsonl").read_text(encoding="utf-8"))
    assert record["provider"] == "claude-code"
    assert record["label"] == "claude-code-aggregate"
    assert payload["input_tokens"] == 420
    assert payload["uncached_input_tokens"] == 100
    assert payload["claude_reported_cost_usd"] == 1.25
    assert payload["cost_usd"] == 1.25
    assert payload["pricing"] == {"source": "provider_reported", "currency": "USD"}
    assert payload["estimated_cost_usd"] != payload["cost_usd"]


